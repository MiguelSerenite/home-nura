/**
 * Writes lib/market-pages/registry.ts: one static import per page file in
 * data/market-pages/{locale}/{slug}.json, so the pages build from bundled
 * data (no file system read at run time).
 *
 * Run after adding, renaming or removing a page file:
 *   npx tsx scripts/market-pages/sync-registry.ts
 * then validate every page:
 *   npx vitest run tests/lib/market-pages
 * tests/lib/market-pages/data.test.ts fails while the registry and the
 * folder disagree.
 */

import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
export const DATA_DIR = join(ROOT, 'data', 'market-pages')
export const REGISTRY_FILE = join(ROOT, 'lib', 'market-pages', 'registry.ts')

export interface PageFileName {
  locale: string
  slug: string
}

/** Page files on disk, sorted by locale then slug. */
export function pageFilesOnDisk(dir: string = DATA_DIR): PageFileName[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((locale) => statSync(join(dir, locale)).isDirectory())
    .sort()
    .flatMap((locale) =>
      readdirSync(join(dir, locale))
        .filter((name) => name.endsWith('.json'))
        .sort()
        .map((name) => ({ locale, slug: name.slice(0, -'.json'.length) })),
    )
}

function identifier({ locale, slug }: PageFileName): string {
  return `page_${locale}_${slug}`.replace(/[^A-Za-z0-9_]/g, '_')
}

/** Source of lib/market-pages/registry.ts for these files. */
export function registrySource(files: readonly PageFileName[]): string {
  const imports = files.map((file) => `import ${identifier(file)} from '@/data/market-pages/${file.locale}/${file.slug}.json'`)
  const entries = files.map((file) => `  { locale: '${file.locale}', slug: '${file.slug}', raw: ${identifier(file)} },`)
  return [
    '/**',
    ' * Market page files (data/market-pages/{locale}/{slug}.json), bundled.',
    ' * Generated by scripts/market-pages/sync-registry.ts: do not edit by hand.',
    ' */',
    '',
    ...imports,
    ...(imports.length > 0 ? [''] : []),
    "import type { RawMarketPageFile } from './types'",
    '',
    'export const MARKET_PAGE_FILES: readonly RawMarketPageFile[] = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

if (process.argv[1]?.endsWith('sync-registry.ts')) {
  const files = pageFilesOnDisk()
  writeFileSync(REGISTRY_FILE, registrySource(files))
  console.log(`lib/market-pages/registry.ts: ${files.length} page file${files.length === 1 ? '' : 's'}`)
}
